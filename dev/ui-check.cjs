const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const {pathToFileURL} = require('node:url');
(async () => {
  const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const page = await browser.newPage({viewport:{width:1280,height:1100},deviceScaleFactor:1});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve(__dirname,'../index.html')).href);
  await page.getByText('100 значений · 63 байта', {exact:false}).waitFor();
  assert((await page.locator('#stats').innerText()).includes('изменено упаковкой: 0'));
  assert((await page.locator('#finding').innerText()).includes('Рисунок симметричен'));
  await page.screenshot({path:path.join(__dirname,'../screenshot.png'),fullPage:true});
  await page.getByLabel('Заготовка',{exact:true}).selectOption('fit-0');
  assert.equal(await page.locator('#span').inputValue(),'18');
  assert((await page.locator('#finding').innerText()).includes('Рисунок симметричен'));
  const original=await page.locator('#data').inputValue();
  const box=await page.getByRole('img',{name:'Редактор полосок',exact:true}).boundingBox();
  await page.mouse.move(box.x+box.width*.41,box.y+box.height*.1);await page.mouse.down();
  await page.mouse.move(box.x+box.width*.58,box.y+box.height*.25,{steps:12});await page.mouse.up();
  assert.notEqual(await page.locator('#data').inputValue(),original);
  await page.getByRole('button',{name:'Отменить',exact:true}).click();
  assert.equal(await page.locator('#data').inputValue(),original);
  await page.getByLabel('Заготовка',{exact:true}).selectOption('fit-1');
  await page.getByLabel('Ширина волны в чате, dp',{exact:true}).fill('240');
  assert((await page.locator('#stats').innerText()).includes('80 полосок'));
  const saved=await page.locator('#data').inputValue();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'JSON',exact:true}).click();
  const download=await downloadPromise;const file=path.join(__dirname,'export-check.json');await download.saveAs(file);
  const data=JSON.parse(fs.readFileSync(file,'utf8'));assert.equal(data.levels.length,100);assert.equal(data.width,240);
  await page.getByRole('button',{name:'Очистить',exact:true}).click();
  await page.locator('#import').setInputFiles(file);
  await page.getByRole('status').filter({hasText:'Рисунок открыт'}).waitFor();
  assert.equal(await page.locator('#data').inputValue(),saved);
  const svgPromise=page.waitForEvent('download');await page.getByRole('button',{name:'SVG сравнения',exact:true}).click();
  const svg=await svgPromise;await svg.saveAs(path.join(__dirname,'export-check.svg'));
  assert(fs.readFileSync(path.join(__dirname,'export-check.svg'),'utf8').includes('Telegram Android'));
  await page.getByLabel('Упаковка 5-битных значений',{exact:true}).selectOption('native');
  assert(!(await page.locator('#stats').innerText()).endsWith('изменено упаковкой: 0'));
  await page.setViewportSize({width:390,height:844});
  const size=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth}));
  assert(size.scroll<=size.width+1,JSON.stringify(size));
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: rendering, drawing/undo, width, JSON roundtrip, SVG export, codec comparison, responsive layout; no page errors.');
})().catch(error=>{console.error(error);process.exit(1);});
